dia = int(input("Informe o dia da semana: "))

if dia == 1:
    print("É domingo")

elif dia == 2:
    print("Segunda")

if dia == 3:
    print("Terça")

elif dia == 4:
    print("Quarta")

if dia == 5:
    print("Quinta")

elif dia == 6:
    print("Sexta")

elif dia == 7:
    print("Sábado")

else:
    print("Valor inválido")