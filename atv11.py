numero1 = int(input("Digite o primeiro número inteiro: "))
numero2 = int(input("Digite o segundo número inteiro: "))
numero3 = float(input("Digite um número real: "))

resultado1 = (numero1 * 2) * (numero2 / 2)
resultado2 = (numero1 * 3) + numero3
resultado3 = numero3 ** 3

print(f"O produto do dobro do primeiro pela metade do segundo é: {resultado1}")
print(f"A soma do triplo do primeiro com o terceiro é: {resultado2}")
print(f"O terceiro número elevado ao cubo é: {resultado3}")